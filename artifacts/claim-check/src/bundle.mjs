// Produce the single-file distributable claim-check.mjs (no imports, no deps).
import { readFileSync, writeFileSync } from "node:fs";
const glob = readFileSync("src/glob.mjs", "utf8");
const check = readFileSync("src/check.mjs", "utf8");
const exch = readFileSync("src/check_exchange.mjs", "utf8");
const verify = readFileSync("src/verify.mjs", "utf8");
const stripShebang = (s) => s.replace(/^#![^\n]*\n/, "");
const stripImports = (s) => s.replace(/^import[^\n]*from\s+"\.\/[^"]+";\n/gm, "");
const out = `#!/usr/bin/env node
// claim-check - single-file, offline, zero-dependency counterparty-side scope-conformance checker.
// Generated by src/bundle.mjs. Public domain / MIT. No network. No model. No key. No vendor.
${stripShebang(stripImports(glob))}
${stripShebang(stripImports(check))}
${stripShebang(stripImports(exch))}
${stripShebang(stripImports(verify))}
`;
writeFileSync("claim-check.mjs", out);
console.log("bundled claim-check.mjs", out.length, "bytes");
